#!/usr/bin/env python3
"""Generate the warm-grey token overrides for frappe-ui's light theme.

frappe-ui emits its theme as CSS variables: semantic ones (`--surface-gray-2`,
`--ink-gray-9`, `--outline-gray-1`, ...) that point at a cool gray ramp, plus the
raw ramp itself (`--gray-100`). This script reads frappe-ui's token source,
finds every light-mode variable that resolves to that gray ramp, and re-points
it at the Másquetú warm ramp below. Colour families (blue, green, red, ...) are
left alone: they carry status meaning.

Re-run it whenever the CRM bumps frappe-ui:

    python3 scripts/gen_theme_tokens.py \\
        apps/crm/frontend/node_modules/frappe-ui/tailwind/generated/colors.json

The selector `:root:not([data-theme="dark"])` outranks frappe-ui's `:root` and
`[data-theme="dark"]` rules, so stylesheet order doesn't matter and dark mode
keeps frappe-ui's own palette.
"""

import argparse
import json
import sys
from pathlib import Path

# Másquetú warm ramp, keyed by frappe-ui's gray shade. Values from
# the Másquetú design system (--mq-* tokens) unless marked "derived".
WARM = {
	"50": "#F9F9F8",  # derived: between white and --mq-surface
	"100": "#F3F3F2",  # --mq-surface
	"200": "#E4E4E2",  # --mq-line
	"300": "#D6D3CF",  # derived: between --mq-line and --mq-card-line
	"400": "#A8A39D",  # --mq-card-line
	"500": "#8C847C",  # --mq-on-dark-faint
	"600": "#6A6560",  # --mq-subtle
	"700": "#55524E",  # --mq-muted-2
	"800": "#3A3835",  # --mq-ink-2
	"900": "#1E1C1A",  # derived: between --mq-ink-2 and --mq-ink
	"950": "#121212",  # --mq-ink
}

# frappe-ui's gray-alpha shades are black at varying opacity. Keep each opacity,
# swap black for a warm near-black (derived from the hue of --mq-muted-2).
WARM_ALPHA_RGB = "1E1A16"

SELECTOR = ':root:not([data-theme="dark"])'
DEFAULT_SOURCE = "apps/crm/frontend/node_modules/frappe-ui/tailwind/generated/colors.json"
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "crm_platform/public/css/_tokens.generated.css"


def warm_value(reference, colors):
	"""Return the warm replacement for a `lightMode/gray[-alpha]/<shade>` reference, else None."""
	mode, family, shade = (reference.split("/") + [None, None])[:3]
	if mode != "lightMode":
		return None
	if family == "gray":
		return WARM[shade]
	if family == "gray-alpha":
		alpha = colors["lightMode"]["gray-alpha"][shade][7:9]
		return f"#{WARM_ALPHA_RGB}{alpha}"
	return None


def generate(colors):
	lines = []
	for category, names in colors["themedVariables"]["light"].items():
		for name, reference in names.items():
			value = warm_value(reference, colors)
			if value:
				lines.append(f"  --{category}-{name}: {value}; /* was {reference} */")
	for shade, value in WARM.items():
		lines.append(f"  --gray-{shade}: {value};")
	for shade in colors["lightMode"]["gray-alpha"]:
		lines.append(f"  --gray-alpha-{shade}: {warm_value(f'lightMode/gray-alpha/{shade}', colors)};")
	header = (
		"/* Generated by scripts/gen_theme_tokens.py from frappe-ui's colors.json.\n"
		"   Do not edit by hand: change WARM in the script and re-run it. */\n"
	)
	return header + SELECTOR + " {\n" + "\n".join(lines) + "\n}\n"


def main():
	ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
	ap.add_argument("source", nargs="?", default=DEFAULT_SOURCE, help="frappe-ui tailwind/generated/colors.json")
	ap.add_argument("--out", default=str(DEFAULT_OUT), help="CSS file to write")
	args = ap.parse_args()
	colors = json.loads(Path(args.source).read_text())
	css = generate(colors)
	Path(args.out).write_text(css)
	print(f"wrote {css.count(';')} variables to {args.out}")


if __name__ == "__main__":
	sys.exit(main())
